let cachedDb: BuildFlowDatabase | null = null;

export function getDb(): BuildFlowDatabase {
  if (cachedDb) return cachedDb;
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (fs.existsSync(DB_FILE)) {
    try {
      const raw = fs.readFileSync(DB_FILE, 'utf-8');
      cachedDb = JSON.parse(raw) as BuildFlowDatabase;
      return cachedDb;
    } catch {
      cachedDb = createSeedDatabase();
      saveDb();
      return cachedDb;
    }
  }
  cachedDb = createSeedDatabase();
  saveDb();
  return cachedDb;
}

export function saveDb(): void {
  if (!cachedDb) return;
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  fs.writeFileSync(DB_FILE, JSON.stringify(cachedDb, null, 2), 'utf-8');
}

export function resetDb(): BuildFlowDatabase {
  cachedDb = createSeedDatabase();
  saveDb();
  return cachedDb;
}
